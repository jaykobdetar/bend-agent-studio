import assert from 'node:assert/strict';
import fs from 'node:fs';
import {pathToFileURL} from 'node:url';
import path from 'node:path';

const worldFile = new URL('../../worlds/benchmarks/matrix-games/world.bend', import.meta.url);
const manifestFile = new URL('../../experiments/matrix-games.json', import.meta.url);
const catalogFile = new URL('../../worlds/benchmarks/matrix-games/games.json', import.meta.url);
export const catalog = JSON.parse(fs.readFileSync(catalogFile, 'utf8'));
export const games = Object.entries(catalog).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const number = (x) => (x < 0 ? 'F32.neg(' + -x + '.0)' : x + '.0');
const cases = (parts) => parts.map(([key, value]) => '    case ' + key + ': ' + value).join('\n');

export function generate() {
  assert(games.length && games.length <= 32, 'matrix catalog must contain 1–32 games');
  for (const [id, matrix] of games) {
    assert(/^[a-z][a-z0-9-]{0,35}$/.test(id), 'invalid matrix ID');
    assert(matrix.length && matrix.length <= 6 && matrix[0].length && matrix[0].length <= 6);
    for (const row of matrix)
      assert(
        row.length === matrix[0].length &&
          row.every((v) => Number.isInteger(v) && Math.abs(v) <= 32767),
      );
  }
  const states = games.map(([id, matrix], index) => [id, matrix.length, matrix[0].length, index]);
  const dimensions = (axis) => cases(states.map((row) => [row[3], row[axis]]));
  const payoffs = cases(
    games.flatMap(([, matrix], id) =>
      matrix.flatMap((row, r) => row.map((value, c) => [id + ' ' + r + ' ' + c, number(value)])),
    ),
  );
  const maxGame = states.length - 1;
  const world = `# Generated by tools/matrix-games/generate.mjs; the JSON catalog is the source.
import Base
import ../../../core/engine.bend as E
import ../../../core/parameters.bend as P

type State is Data:
  Committed{game: U32, seat: U32, other: U32}
  Revealed{joint: U32}

def Observation() -> Data: U32

def rows(game: U32) -> U32:
  match game:
${dimensions(1)}
    case _: 1

def columns(game: U32) -> U32:
  match game:
${dimensions(2)}
    case _: 1

def payoff(game: U32, row: U32, column: U32) -> F32:
  match game row column:
${payoffs}
    case _ _ _: 0.0

def legal(n: Nat, +i: U32) -> List<&2,U32>:
  match n:
    case 0n: []
    case 1n+rest: i <> legal(rest,U32.add(i,1))

# The other seat commits at reset to a private independently salted draw.
# Neither the trained seat's state observation nor its legal list reveals it.
def start(+game: U32,+seat: U32,seed: U32) -> State:
  count=Bool.pick(U32,U32.is_eq(seat,0),columns(game),rows(game))
  Committed{game,seat,U32.mod(E.mix_word(U32.xor(seed,3758096513)),count)}

def inspect(state: State) -> E.View<U32>:
  match state:
    case Committed{+game,seat,other}:
      E.Open{0,legal(U32.to_nat(Bool.pick(U32,U32.is_eq(seat,0),rows(game),columns(game))),0)}
    case Revealed{joint}: E.End{joint}

def settlement(+game: U32,+row: U32,+column: U32,second: Bool) -> Pair(State,F32):
  +value=payoff(game,row,column)
  joint=U32.add(1,U32.add(U32.mul(row,columns(game)),column))
  (Revealed{joint},Bool.pick(F32,second,F32.neg(value),value))

def move(state: State,+action: U32,word: U32) -> Pair(State,F32):
  match state:
    case Committed{game,0,other}: settlement(game,action,other,False{})
    case Committed{game,1,other}: settlement(game,other,action,True{})
    case same: (same,0.0)

def world(+p: P.Parameters) -> E.World<State,Observation>:
  +game=F32.to_u32(F32.max(0.0,F32.min(${maxGame}.0,P.get(p,"game",0.0))))
  +seat=F32.to_u32(F32.max(0.0,F32.min(1.0,P.get(p,"seat",0.0))))
  E.World{start(game,seat),inspect,action => a => w => move(action,a,w)}
`;
  // Bend import file names are rooted where the generated module lives.
  const plan = {
    schema: 1,
    name: 'matrix-games',
    games: states.flatMap(([id, , , game]) =>
      ['row', 'column'].map((side, seat) => ({
        id: id + '-' + side,
        domain: 'discrete',
        worldFile: '../worlds/benchmarks/matrix-games/world.bend',
        limit: 1,
        parameters: {game, seat},
      })),
    ),
    arms: [
      {id: 'uniform', method: 'random'},
      {id: 'q-learning', method: 'q_learning', epsilon: 0.25, alpha: 0.125, gamma: 0},
    ],
    replicates: 4,
    checkpoints: [0, 16, 64],
    validationEpisodes: 4,
    testEpisodes: 4,
    seeds: {train: 223000000, validation: 1223000000, test: 2223000000, stride: 10000},
  };
  return [
    [worldFile, world],
    [manifestFile, JSON.stringify(plan, null, 2) + '\n'],
  ];
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const flag = process.argv[2] ?? '--check';
  assert(
    process.argv.length <= 3 && ['--write', '--check'].includes(flag),
    'use --write or --check',
  );
  for (const [url, expected] of generate()) {
    if (flag === '--write') fs.writeFileSync(url, expected);
    else
      assert.equal(fs.readFileSync(url, 'utf8').replaceAll('\r\n', '\n'), expected, url.pathname);
  }
}
